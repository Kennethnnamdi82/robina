import { expect, test } from '@playwright/test';

const entry = '/tests/rivals/index.html';
test('menu routes, mission briefing and persistent settings work without loading Phaser', async ({ page }, info) => {
  const engines: string[] = [];
  page.on('request', request => { if (/phaser|createGame/.test(request.url())) engines.push(request.url()); });
  await page.goto(entry);
  await page.getByRole('button', { name: 'PLAY', exact: true }).focus();
  await page.keyboard.press('ArrowDown'); await expect(page.getByRole('button', { name: /MISSIONS/ })).toBeFocused();
  await page.keyboard.press('Enter');
  await expect(page.getByRole('heading', { name: 'Choose your approach.' })).toBeVisible();
  await expect(page.getByText('This operation is not available yet.')).toHaveCount(2);
  await page.getByRole('button', { name: /VIEW BRIEFING/ }).click();
  await expect(page.getByRole('region', { name: 'Mission briefing' })).toBeVisible();
  await expect(page.getByText('100 practice XP + 25 optional recon XP')).toBeVisible();
  await page.getByRole('button', { name: 'Select NYX' }).click();
  await expect(page.getByRole('img', { name: 'NYX character preview' })).toBeVisible();
  await page.screenshot({ path: info.outputPath('briefing-desktop.png'), fullPage: true });
  await page.getByRole('button', { name: 'Back to main menu' }).click();
  await page.getByRole('button', { name: 'SETTINGS', exact: true }).click();
  await page.getByLabel('Master volume', { exact: true }).fill('42');
  await page.getByLabel('Music volume', { exact: true }).fill('18');
  await page.getByLabel('Sound effects volume', { exact: true }).fill('63');
  await page.getByLabel('Mute all audio').uncheck();
  await page.getByLabel('Mobile controls', { exact: true }).selectOption('show');
  await page.getByLabel('Motion preference').selectOption('reduce');
  await page.getByLabel('High contrast HUD').check();
  await page.reload(); await page.getByRole('button', { name: 'SETTINGS', exact: true }).click();
  await expect(page.getByLabel('Master volume', { exact: true })).toHaveValue('42');
  await expect(page.getByLabel('Music volume', { exact: true })).toHaveValue('18');
  await expect(page.getByLabel('Mobile controls', { exact: true })).toHaveValue('show');
  await expect(page.getByLabel('High contrast HUD')).toBeChecked();
  await page.screenshot({ path: info.outputPath('settings-desktop.png'), fullPage: true });
  await page.getByRole('button', { name: 'Back to main menu' }).click();
  await page.getByRole('button', { name: 'CHARACTER CUSTOMIZATION' }).click();
  await expect(page.getByRole('button', { name: 'Select NYX' })).toHaveAttribute('aria-pressed', 'true');
  await page.getByRole('button', { name: 'Select ROOK' }).click();
  await page.getByRole('button', { name: 'Back to main menu' }).click();
  await page.getByRole('button', { name: /LEADERBOARDS/ }).click();
  await expect(page.getByText('Rival rankings are not live yet.')).toBeVisible();
  await expect(page.getByRole('link', { name: /existing community leaderboard/ })).toHaveAttribute('href', '/rank');
  await page.getByRole('button', { name: 'Back to main menu' }).click();
  await expect(page.getByRole('link', { name: 'PLAYER PROFILE' })).toHaveAttribute('href', '/profile');
  expect(engines).toEqual([]);
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true);
  await page.screenshot({ path: info.outputPath('main-menu-desktop.png'), fullPage: true });
});
